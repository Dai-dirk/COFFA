"""
Python reconstruction of CSA_tree.v execution flow.

- Generates Booth partial products (pp0, pp1, pp2)
- Builds CSA tree operands with/without truncation (TRG)
- Runs CSA_38 and CPA_38 stages one-to-one with the Verilog
- Supports VEC path by deriving A0..A3,b via the APP module mapping from converter/converter.py
- All bit-vectors are represented as binary strings (MSB-first), zero-padded to fixed widths
"""

from typing import Tuple, List
import os
import importlib.util


# -------------------- Bitstring helpers --------------------

def int_to_bin(value: int, width: int) -> str:
    return format(value & ((1 << width) - 1), f"0{width}b")


def bin_to_int(bits: str) -> int:
    return int(bits, 2) if bits else 0


def zfill_width(bits: str, width: int) -> str:
    if len(bits) < width:
        return bits.zfill(width)
    return bits[-width:]


def sign_extend(bits: str, src_width: int, dst_width: int) -> str:
    bits = zfill_width(bits, src_width)
    sign = bits[0]
    if dst_width <= src_width:
        return bits[-dst_width:]
    return (sign * (dst_width - src_width)) + bits


def left_shift_1(bits: str, width: int) -> str:
    bits = zfill_width(bits, width)
    return (bits[1:] + '0')[-width:] 


def concat_str(*parts: str) -> str:
    return ''.join(parts)


def slice_msb_lsb(bits: str, msb: int, lsb: int) -> str:
    # bits[0] is MSB; verilog [msb:lsb]
    n = len(bits)
    start = n - 1 - msb
    end = n - 1 - lsb
    if start < 0:
        bits = bits.zfill(n - start)
        n = len(bits)
        start = n - 1 - msb
        end = n - 1 - lsb
    out = bits[start:end + 1]
    return out


# -------------------- CSA_38 and CPA_38 --------------------

def csa_38(a: str, b: str, c: str) -> Tuple[str, str]:
    width = 38
    a_i = bin_to_int(zfill_width(a, width))
    b_i = bin_to_int(zfill_width(b, width))
    c_i = bin_to_int(zfill_width(c, width))
    sum_i = (a_i ^ b_i) ^ c_i
    carry_i = (a_i & b_i) | (b_i & c_i) | (c_i & a_i)
    return int_to_bin(sum_i, width), int_to_bin(carry_i, width)


def cpa_38(a: str, b: str) -> str:
    width = 38
    a_i = bin_to_int(zfill_width(a, width))
    b_i = bin_to_int(zfill_width(b, width))
    s = (a_i + b_i) & ((1 << width) - 1)
    return int_to_bin(s, width)


# -------------------- LOGC: ABS, LOD, APP(csa mapping) --------------------

def abs32(x32: str) -> Tuple[str, str]:
    x32 = zfill_width(x32, 32)
    sign = x32[0]
    if sign == '1':
        inv = ''.join('1' if b == '0' else '0' for b in x32)
        val = bin_to_int(inv) + 1
        return '1', int_to_bin(val, 32)
    return '0', x32


def leading_one_32(x32: str) -> str:
    x32 = zfill_width(x32, 32)
    for pos in range(31, -1, -1):
        if x32[31 - pos] == '1':
            return int_to_bin(pos, 5)
    return '00000'

def bin_str_extract(bin_str, high, low):
    """
    提取二进制字符串的指定位范围 [high:low]
    Verilog中，x_in[high:low]表示从高位high到低位low的位范围
    假设输入是标准二进制字符串（从左到右，索引0是MSB）
    对于32位：bin_str[0]对应Verilog的x_in[31]，bin_str[31]对应Verilog的x_in[0]
    对于22位：bin_str[0]对应Verilog的f[21]，bin_str[21]对应Verilog的f[0]
    
    因此，Verilog的bit[high]对应Python的bin_str[总位数-1-high]
    """
    if len(bin_str) < high + 1:
        bin_str = bin_str.zfill(high + 1)
    
    total_bits = len(bin_str)
    # Verilog的high位对应Python索引(total_bits-1-high)
    # Verilog的low位对应Python索引(total_bits-1-low)
    py_high = total_bits - 1 - high
    py_low = total_bits - 1 - low
    
    # 提取从py_high到py_low（包括两端），注意Python切片是左闭右开
    if py_high <= py_low:
        extracted = bin_str[py_high:py_low+1]
    else:
        # 如果high < low，需要反转
        extracted = bin_str[py_low:py_high+1]
        extracted = extracted[::-1]  # 反转以保持高位在前
    
    return extracted

def leading_one_detector_4bit(in_4bit):
    """4位前导1检测器"""
    if len(in_4bit) != 4:
        in_4bit = in_4bit.zfill(4)
    
    if in_4bit == '0000':
        signal = '0'
        msb_pos = '00'
    elif in_4bit[0] == '1':
        signal = '1'
        msb_pos = '11'
    elif in_4bit[1] == '1':
        signal = '1'
        msb_pos = '10'
    elif in_4bit[2] == '1':
        signal = '1'
        msb_pos = '01'
    else:
        signal = '1'
        msb_pos = '00'
    
    return msb_pos, signal

def leading_one_detector_32(x_in):
    """32位前导1检测器"""
    if len(x_in) != 32:
        x_in = x_in.zfill(32)
    
    # 分成8组，每组4位
    groups = [
        x_in[0:4],   # [31:28]
        x_in[4:8],   # [27:24]
        x_in[8:12],  # [23:20]
        x_in[12:16], # [19:16]
        x_in[16:20], # [15:12]
        x_in[20:24], # [11:8]
        x_in[24:28], # [7:4]
        x_in[28:32]  # [3:0]
    ]
    
    msb_groups = []
    signals = []
    
    for group in groups:
        msb_pos, signal = leading_one_detector_4bit(group)
        msb_groups.append(msb_pos)
        signals.append(signal)
    
    # 找到第一个有信号的分组
    if signals[0] == '1':
        msb_pos = '111' + msb_groups[0]
    elif signals[1] == '1':
        msb_pos = '110' + msb_groups[1]
    elif signals[2] == '1':
        msb_pos = '101' + msb_groups[2]
    elif signals[3] == '1':
        msb_pos = '100' + msb_groups[3]
    elif signals[4] == '1':
        msb_pos = '011' + msb_groups[4]
    elif signals[5] == '1':
        msb_pos = '010' + msb_groups[5]
    elif signals[6] == '1':
        msb_pos = '001' + msb_groups[6]
    elif signals[7] == '1':
        msb_pos = '000' + msb_groups[7]
    else:
        msb_pos = '00000'
    
    return msb_pos

def lod_module(x_in):
    """
    LOD0模块: Leading One Detector
    输入: 32位二进制字符串
    输出: k (5位), f (22位), zero_signal (1位)
    """
    if len(x_in) != 32:
        x_in = x_in.zfill(32)
    
    # 检查是否为0
    if x_in == '0' * 32:
        return '00000', '0' * 22, '1'
    
    # 找到最高位1的位置
    k = leading_one_detector_32(x_in)
    k_int = bin_to_int(k)
    
    # 根据k提取f
    f_map = {
        31: bin_str_extract(x_in, 30, 9),   # x_in[30:9]
        30: bin_str_extract(x_in, 29, 8),   # x_in[29:8]
        29: bin_str_extract(x_in, 28, 7),   # x_in[28:7]
        28: bin_str_extract(x_in, 27, 6),   # x_in[27:6]
        27: bin_str_extract(x_in, 26, 5),   # x_in[26:5]
        26: bin_str_extract(x_in, 25, 4),   # x_in[25:4]
        25: bin_str_extract(x_in, 24, 3),   # x_in[24:3]
        24: bin_str_extract(x_in, 23, 2),   # x_in[23:2]
        23: bin_str_extract(x_in, 22, 1),   # x_in[22:1]
        22: bin_str_extract(x_in, 21, 0),   # x_in[21:0]
        21: bin_str_extract(x_in, 20, 0) + '0',  # {x_in[20:0], 1'b0}
        20: bin_str_extract(x_in, 19, 0) + '00',  # {x_in[19:0], 2'b0}
        19: bin_str_extract(x_in, 18, 0) + '000',  # {x_in[18:0], 3'b0}
        18: bin_str_extract(x_in, 17, 0) + '0000',  # {x_in[17:0], 4'b0}
        17: bin_str_extract(x_in, 16, 0) + '00000',  # {x_in[16:0], 5'b0}
        16: bin_str_extract(x_in, 15, 0) + '000000',  # {x_in[15:0], 6'b0}
        15: bin_str_extract(x_in, 14, 0) + '0000000',  # {x_in[14:0], 7'b0}
        14: bin_str_extract(x_in, 13, 0) + '00000000',  # {x_in[13:0], 8'b0}
        13: bin_str_extract(x_in, 12, 0) + '000000000',  # {x_in[12:0], 9'b0}
        12: bin_str_extract(x_in, 11, 0) + '0000000000',  # {x_in[11:0], 10'b0}
        11: bin_str_extract(x_in, 10, 0) + '00000000000',  # {x_in[10:0], 11'b0}
        10: bin_str_extract(x_in, 9, 0) + '000000000000',  # {x_in[9:0], 12'b0}
        9: bin_str_extract(x_in, 8, 0) + '0000000000000',  # {x_in[8:0], 13'b0}
        8: bin_str_extract(x_in, 7, 0) + '00000000000000',  # {x_in[7:0], 14'b0}
        7: bin_str_extract(x_in, 6, 0) + '000000000000000',  # {x_in[6:0], 15'b0}
        6: bin_str_extract(x_in, 5, 0) + '0000000000000000',  # {x_in[5:0], 16'b0}
        5: bin_str_extract(x_in, 4, 0) + '00000000000000000',  # {x_in[4:0], 17'b0}
        4: bin_str_extract(x_in, 3, 0) + '000000000000000000',  # {x_in[3:0], 18'b0}
        3: bin_str_extract(x_in, 2, 0) + '0000000000000000000',  # {x_in[2:0], 19'b0}
        2: bin_str_extract(x_in, 1, 0) + '00000000000000000000',  # {x_in[1:0], 20'b0}
        1: x_in[31] + '000000000000000000000',  # {x_in[0], 21'b0}
        0: '0' * 22  # {22'b0}
    }
    
    f = f_map.get(k_int, '0' * 22)
    if len(f) > 22:
        f = f[-22:]
    elif len(f) < 22:
        f = f.zfill(22)
    
    zero_signal = '0'
    return k, f, zero_signal

