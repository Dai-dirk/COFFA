def logc(y32: str, n5: str, float_flag: str) -> Tuple[str, str, str, str, str, str, str, str]:
    sign, abs_y = abs32(y32)
    k, f, zero_signal0 = lod_module(abs_y)
    input_app_f = f if float_flag == '0' else slice_msb_lsb(y32, 22, 1)
    A0, A1, A2, A3, b = app_csa_map(input_app_f)
    sub_a = ('000' + k) if float_flag == '0' else slice_msb_lsb(y32, 30, 23)
    sub_b = ('000' + zfill_width(n5, 5)) if float_flag == '0' else int_to_bin(0x7F, 8)
    k8 = int_to_bin((bin_to_int(sub_a) - bin_to_int(sub_b)) & 0xFF, 8)
    zero_signal = '1' if (float_flag == '0' and zero_signal0 == '1') else '0'
    return zero_signal, sign, k8, A0, A1, A2, A3, b


# -------------------- Booth partial products --------------------

def booth_pp(input7: str, trg: str, A31: str, revA31: str) -> Tuple[str, str, str]:
    input7 = zfill_width(input7, 7)
    A31 = zfill_width(A31, 31)
    revA31 = zfill_width(revA31, 31)

    # onehot windows
    if trg == '0':
        one0 = input7[4:7]  # input_7[2:0]
    else:
        one0 = (input7[4:6] + '0')  # {input_7[2:1], 1'b0}
    one1 = input7[2:5] # [4:2]
    one2 = input7[0:3] # [6:4]
    # print("input7:", input7)
    # print("one0:", one0)
    # print("one1:", one1)
    # print("one2:", one2)
    # pp0 (34 bits)
    a30 = A31[0]
    if one0 in ('000', '111'):
        pp0 = '100' + '0' * 31
    elif one0 in ('001', '010'):
        pp0 = ('100' if a30 == '0' else '011') + A31
    elif one0 == '011':
        pp0 = ('100' if a30 == '0' else '011') + A31[1:] + '0'
    elif one0 == '100':
        # rev_A with shift
        head = '011' if a30 == '0' else '100'
        pp0 = head + revA31[0] + revA31[2:] + '0'
    elif one0 in ('101', '110'):
        head = '011' if a30 == '0' else '100'
        pp0 = head + revA31
    else:
        pp0 = '0' * 34

    # pp1 (33 bits)
    S = '1' if A31[0] == '0' else '0'
    S_ = '0' if A31[0] == '0' else '1'
    if one1 in ('000', '111'):
        pp1 = '11' + '0' * 31
    elif one1 in ('001', '010'):
        pp1 = '1' + S + A31
    elif one1 == '011':
        pp1 = '1' + S + A31[1:] + '0'
    elif one1 == '100':
        pp1 = '1' + S_ + revA31[0] + revA31[2:] + '0'
    elif one1 in ('101', '110'):
        pp1 = '1' + S_ + revA31
    else:
        pp1 = '0' * 33

    # pp2 (34 bits)
    if one2 in ('000', '111'):
        pp2 = '11' + '1' + '0' * 31
    elif one2 in ('001', '010'):
        pp2 = '11' + S + A31
    elif one2 == '011':
        pp2 = '11' + S + A31[1:] + '0'
    elif one2 == '100':
        pp2 = '11' + S_ + revA31[0] + revA31[2:] + '0'
    elif one2 in ('101', '110'):
        pp2 = '11' + S_ + revA31
    else:
        pp2 = '0' * 34

    return zfill_width(pp0, 34), zfill_width(pp1, 33), zfill_width(pp2, 34)


