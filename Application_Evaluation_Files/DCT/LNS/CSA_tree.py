    float_flag = '1' if float_flag in (1, True, '1') else '0'
    B0_32 = zfill_width(B0_32, 32)
    log_c1_30 = zfill_width(log_c1_30, 30)
    log_c2_30 = zfill_width(log_c2_30, 30)
    log_c3_30 = zfill_width(log_c3_30, 30)
    log_c4_30 = zfill_width(log_c4_30, 30)
    log_c5_30 = zfill_width(log_c5_30, 30)
    TRG = '1' if TRG in (1, True, '1') else '0'
    VEC = '1' if VEC in (1, True, '1') else '0'
    # print("TRG:", TRG)
    # print("VEC:", VEC)

    # Extend A to 31 bits: {A[29], A[29:0]}
    extend_A31 = A32[2] + A32[2:32]
    revA31_i = ((~bin_to_int(extend_A31)) + 1) & ((1 << 31) - 1)
    revA31 = int_to_bin(revA31_i, 31)

    # print("extend_A31:", extend_A31)
    # print("revA31:", revA31)

    # Booth windows
    in0 = B30[24:30] + '0'  # {B[5:0], 1'b0}
    in1 = B30[18:25]     # B[11:5]
    in2 = B30[12:19]    # B[17:11]
    in3 = B30[6:13]    # B[23:17]
    in4 = B30[0:7]    # B[29:23]
    # print("B30:", B30)
    # print("in0:", in0)
    # print("in1:", in1)
    # print("in2:", in2)
    # print("in3:", in3)
    # print("in4:", in4)

    pp0_0, pp1_0, pp2_0 = booth_pp(in0, TRG, extend_A31, revA31)
    pp0_1, pp1_1, pp2_1 = booth_pp(in1, TRG, extend_A31, revA31)
    pp0_2, pp1_2, pp2_2 = booth_pp(in2, TRG, extend_A31, revA31)
    pp0_3, pp1_3, pp2_3 = booth_pp(in3, TRG, extend_A31, revA31)
    pp0_4, pp1_4, pp2_4 = booth_pp(in4, TRG, extend_A31, revA31)

    # print("pp0_0:", pp0_0)
    # print("pp0_1:", pp0_1)
    # print("pp0_2:", pp0_2)
    # print("pp0_3:", pp0_3)
    # print("pp0_4:", pp0_4)
    # print("pp1_0:", pp1_0)
    # print("pp1_1:", pp1_1)
    # print("pp1_2:", pp1_2)
    # print("pp1_3:", pp1_3)
    # print("pp1_4:", pp1_4)
    # print("pp2_0:", pp2_0)
    # print("pp2_1:", pp2_1)
    # print("pp2_2:", pp2_2)
    # print("pp2_3:", pp2_3)
    # print("pp2_4:", pp2_4)
    # CSA operand groups (38 bits each)
    CSA0_op = [None, None, None]  # type: ignore
    CSA1_op = [None, None, None]  # type: ignore
    CSA2_op = [None, None, None]  # type: ignore
    CSA3_op = [None, None, None]  # type: ignore
    CSA4_op = [None, None, None]  # type: ignore

    if TRG == '1':
        CSA0_op[0] = '0000' + pp0_0
        CSA0_op[1] = '000' + pp1_0 + '00'
        CSA0_op[2] = pp2_0 + '0000'

        CSA1_op[0] = '0000' + pp0_1
        CSA1_op[1] = '000' + pp1_1 + '00'
        CSA1_op[2] = pp2_1 + '0000'

        CSA2_op[0] = '0000' + pp0_2
        CSA2_op[1] = '000' + pp1_2 + '00'
        CSA2_op[2] = pp2_2 + '0000'

        CSA3_op[0] = '0000' + pp0_3
        CSA3_op[1] = '000' + pp1_3 + '00'
        CSA3_op[2] = pp2_3 + '0000'

        CSA4_op[0] = '0000' + pp0_4
        CSA4_op[1] = '000' + pp1_4 + '00'
        CSA4_op[2] = pp2_4 + '0000'
    else:
        CSA0_op[0] = '0' * 26 + pp0_0[:12]
        CSA0_op[1] = '0' * 25 + pp1_0[:13]
        CSA0_op[2] = '0' * 23 + pp2_0[1:16]

        CSA1_op[0] = '0' * 21 + '1' + pp0_1[0] + pp0_1[3:18]
        CSA1_op[1] = '0' * 19 + pp1_1[:19]
        CSA1_op[2] = '0' * 17 + pp2_1[1:22]

        CSA2_op[0] = '0' * 15 + '1' + pp0_2[0] + pp0_2[3:24]
        CSA2_op[1] = '0' * 13 + pp1_2[:25]
        CSA2_op[2] = '0' * 11 + pp2_2[1:28]

        CSA3_op[0] = '0' * 9 + '1' + pp0_3[0] + pp0_3[3:30]
        CSA3_op[1] = '0' * 7 + pp1_3[:31]
        CSA3_op[2] = '0' * 5 + pp2_3[1:34]

        CSA4_op[0] = '0' * 3 + '1' + pp0_4[0] + pp0_4[3:] + '00'
        CSA4_op[1] = '0' + pp1_4 + '0000'
        CSA4_op[2] = pp2_4[2:] + '000000'

    # Extend log constants to 38
    def ext30(x30: str) -> str:
        return (('00000000' if x30[0] == '0' else '11111111') + x30)

    extend_log_c0 = ext30(log_c1_30)
    extend_log_c1 = ext30(log_c2_30)
    extend_log_c2 = ext30(log_c3_30)
    extend_log_c3 = ext30(log_c4_30)
    extend_log_c4 = ext30(log_c5_30)

    # print("CSA0_op[0]:", CSA0_op[0])
    # print("CSA0_op[1]:", CSA0_op[1])
    # print("CSA0_op[2]:", CSA0_op[2])
    # print("CSA1_op[0]:", CSA1_op[0])
    # print("CSA1_op[1]:", CSA1_op[1])
    # print("CSA1_op[2]:", CSA1_op[2])
    # print("CSA2_op[0]:", CSA2_op[0])
    # print("CSA2_op[1]:", CSA2_op[1])
    # print("CSA2_op[2]:", CSA2_op[2])
    # print("CSA3_op[0]:", CSA3_op[0])
    # print("CSA3_op[1]:", CSA3_op[1])
    # print("CSA3_op[2]:", CSA3_op[2])
    # print("CSA4_op[0]:", CSA4_op[0])
    # print("CSA4_op[1]:", CSA4_op[1])
    # print("CSA4_op[2]:", CSA4_op[2])
    # print("extend_log_c0:", extend_log_c0)
    # print("extend_log_c1:", extend_log_c1)
    # print("extend_log_c2:", extend_log_c2)
    # print("extend_log_c3:", extend_log_c3)
    # print("extend_log_c4:", extend_log_c4)

    # LOGC
    zero_signal_y0, sign_y0, k0, A0_y0, A1_y0, A2_y0, A3_y0, b_y0 = logc(B0_32, n5, float_flag)
    zero_sign_k0 = ''.join([zero_signal_y0, sign_y0, k0])

    # CSA0..CSA4 (with optional VEC override for CSA0 inputs)
    CSA0_oper = [None, None, None]  # type: ignore
    CSA0_oper[0] = ('0' * 16 + A0_y0) if VEC == '1' else CSA0_op[0]
    CSA0_oper[1] = ('0' * 16 + A1_y0) if VEC == '1' else CSA0_op[1]
    CSA0_oper[2] = ('0' * 16 + A2_y0) if VEC == '1' else CSA0_op[2]
    CSA0_sum, CSA0_carry = csa_38(CSA0_oper[0], CSA0_oper[1], CSA0_oper[2])

    CSA1_sum, CSA1_carry = csa_38(CSA1_op[0], CSA1_op[1], CSA1_op[2])
    CSA2_sum, CSA2_carry = csa_38(CSA2_op[0], CSA2_op[1], CSA2_op[2])
    CSA3_sum, CSA3_carry = csa_38(CSA3_op[0], CSA3_op[1], CSA3_op[2])
    CSA4_sum, CSA4_carry = csa_38(CSA4_op[0], CSA4_op[1], CSA4_op[2])

    CSA5_op_c = CSA3_sum if TRG == '0' else extend_log_c4
    CSA5_sum, CSA5_carry = csa_38(left_shift_1(CSA4_carry, 38), CSA4_sum, CSA5_op_c)

    CSA6_op_c = left_shift_1(CSA3_carry, 38) if TRG == '0' else extend_log_c2
    CSA6_sum, CSA6_carry = csa_38(CSA2_sum, left_shift_1(CSA2_carry, 38), CSA6_op_c)

    CSA7_op_a = CSA0_sum if TRG == '0' else extend_log_c1
    CSA7_sum, CSA7_carry = csa_38(CSA7_op_a, left_shift_1(CSA1_carry, 38), CSA1_sum)

    CSA8_op_a = CSA6_sum if TRG == '0' else left_shift_1(CSA3_carry, 38)
    CSA8_op_b = CSA5_sum if TRG == '0' else CSA3_sum
    CSA8_op_c = left_shift_1(CSA5_carry, 38) if TRG == '0' else extend_log_c3
    CSA8_sum, CSA8_carry = csa_38(CSA8_op_a, CSA8_op_b, CSA8_op_c)

    CSA9_op_b = left_shift_1(CSA7_carry, 38) if TRG == '0' else CSA0_sum
    CSA9_op_c = CSA7_sum if TRG == '0' else (('0' * 16 + A3_y0) if VEC == '1' else extend_log_c0)
    CSA9_sum, CSA9_carry = csa_38(left_shift_1(CSA0_carry, 38), CSA9_op_b, CSA9_op_c)

    CSA10_sum, CSA10_carry = csa_38(left_shift_1(CSA6_carry, 38), CSA8_sum, left_shift_1(CSA8_carry, 38))
    CSA11_sum, CSA11_carry = csa_38(CSA9_sum, left_shift_1(CSA10_carry, 38), CSA10_sum)

    CSA12_op_b = CSA9_sum if VEC == '1' else left_shift_1(CSA11_carry, 38)
    CSA12_op_c = ('0' * 16 + b_y0) if VEC == '1' else CSA11_sum
    CSA12_sum, CSA12_carry = csa_38(left_shift_1(CSA9_carry, 38), CSA12_op_b, CSA12_op_c)

    # CPA outputs
    cpa0_select = (TRG == '0') or (VEC == '1')
    cpa0_a = left_shift_1(CSA12_carry, 38) if cpa0_select else left_shift_1(CSA9_carry, 38)
    cpa0_b = CSA12_sum if cpa0_select else CSA9_sum
    cpa_channel0_temp = cpa_38(cpa0_a, cpa0_b)
    # Saturation select
    cpa_channel0_select = (VEC == '1') and (A0_y0[0] == '1') and (cpa_channel0_temp[0] == '0')
    if cpa_channel0_select:
        cpa_channel0 = cpa_channel0_temp[:16] + '1' * 22
    else:
        cpa_channel0 = cpa_channel0_temp

    cpa_channel1 = cpa_38(CSA7_sum, left_shift_1(CSA7_carry, 38))
    cpa_channel2 = cpa_38(CSA6_sum, left_shift_1(CSA6_carry, 38))
    cpa_channel3 = cpa_38(CSA8_sum, left_shift_1(CSA8_carry, 38))
    cpa_channel4 = cpa_38(CSA5_sum, left_shift_1(CSA5_carry, 38))
    # print("cpa_channel0:", cpa_channel0)
    # print("cpa_channel1:", cpa_channel1)
    # print("cpa_channel2:", cpa_channel2)
    # print("cpa_channel3:", cpa_channel3)
    # print("cpa_channel4:", cpa_channel4)

    return zero_sign_k0, cpa_channel0, cpa_channel1, cpa_channel2, cpa_channel3, cpa_channel4


