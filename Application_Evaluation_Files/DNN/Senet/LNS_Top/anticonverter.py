def csa_anticonv(a, b, c, width=21):
    """
    CSA (Carry Save Adder) 模块 - anticonverter版本
    输入: a, b, c (21位二进制字符串)
    输出: sum, carry (21位二进制字符串)
    """
    if len(a) < width:
        a = a.zfill(width)
    if len(b) < width:
        b = b.zfill(width)
    if len(c) < width:
        c = c.zfill(width)
    
    a = a[-width:]
    b = b[-width:]
    c = c[-width:]
    
    # sum = a ^ b ^ c
    sum_val = bin_to_int(a) ^ bin_to_int(b) ^ bin_to_int(c)
    sum_str = int_to_bin(sum_val, width)
    
    # carry = (a & b) | (b & c) | (c & a)
    carry_val = (bin_to_int(a) & bin_to_int(b)) | (bin_to_int(b) & bin_to_int(c)) | (bin_to_int(c) & bin_to_int(a))
    carry_str = int_to_bin(carry_val, width)
    
    return sum_str, carry_str

def cpa_anticonv(a, b, width=21):
    """
    CPA (Carry Propagate Adder) 模块 - anticonverter版本
    输入: a, b (21位二进制字符串)
    输出: sum (21位二进制字符串)
    """
    if len(a) < width:
        a = a.zfill(width)
    if len(b) < width:
        b = b.zfill(width)
    
    a = a[-width:]
    b = b[-width:]
    
    # sum = a + b
    sum_val = (bin_to_int(a) + bin_to_int(b)) & ((1 << width) - 1)
    return int_to_bin(sum_val, width)

