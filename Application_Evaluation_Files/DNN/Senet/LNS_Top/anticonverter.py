"""
Verilog anticonverter的Python实现
输入: 32位二进制字符串x, 是否计算浮点的float_flag, 溢出标志Tri_overflow_one, 定点小数位数n
输出: 32位二进制字符串x_output（反对数）
"""

def int_to_bin(val, width):
    """将整数转换为指定位宽的二进制字符串"""
    return format(val & ((1 << width) - 1), f'0{width}b')

def bin_to_int(bin_str):
    """将二进制字符串转换为整数"""
    return int(bin_str, 2)

def bin_str_extract(bin_str, high, low):
    """
    提取二进制字符串的指定位范围 [high:low]
    Verilog中，x[high:low]表示从高位high到低位low的位范围
    假设输入是标准二进制字符串（从左到右，索引0是MSB）
    """
    if len(bin_str) < high + 1:
        bin_str = bin_str.zfill(high + 1)
    
    total_bits = len(bin_str)
    py_high = total_bits - 1 - high
    py_low = total_bits - 1 - low
    
    if py_high <= py_low:
        extracted = bin_str[py_high:py_low+1]
    else:
        extracted = bin_str[py_low:py_high+1]
        extracted = extracted[::-1]
    
    return extracted

def bin_str_negate(bin_str):
    """对二进制字符串按位取反"""
    return ''.join('1' if b == '0' else '0' for b in bin_str)

def bin_str_add(bin_str1, bin_str2, width):
    """二进制字符串加法"""
    val1 = bin_to_int(bin_str1) if len(bin_str1) <= width else bin_to_int(bin_str1[-width:])
    val2 = bin_to_int(bin_str2) if len(bin_str2) <= width else bin_to_int(bin_str2[-width:])
    result = (val1 + val2) & ((1 << width) - 1)
    return int_to_bin(result, width)

def bin_str_sub(bin_str1, bin_str2, width):
    """二进制字符串减法"""
    val1 = bin_to_int(bin_str1) if len(bin_str1) <= width else bin_to_int(bin_str1[-width:])
    val2 = bin_to_int(bin_str2) if len(bin_str2) <= width else bin_to_int(bin_str2[-width:])
    result = (val1 - val2) & ((1 << width) - 1)
    return int_to_bin(result, width)

