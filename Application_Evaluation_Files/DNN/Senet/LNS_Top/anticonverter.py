        csa3_sum, csa3_carry = csa_anticonv(csa2_sum, b_str, csa2_carry_shifted)
        
        # CPA: csa3_sum, {csa3_carry[19:0], 1'b0}
        csa3_carry_low20 = csa3_carry[1:] if len(csa3_carry) >= 21 else csa3_carry[1:].zfill(20)
        csa3_carry_shifted = (csa3_carry_low20 + '0')[:21].zfill(21)
        final_sum = cpa_anticonv(csa3_sum, csa3_carry_shifted)
        
        # f_e2_out = {final_sum, f[1:0]}
        f_low2 = bin_str_extract(f, 1, 0)
        f_e2_out = final_sum + f_low2
        
        # 确保是23位
        if len(f_e2_out) > 23:
            f_e2_out = f_e2_out[:23]
        elif len(f_e2_out) < 23:
            f_e2_out = f_e2_out.zfill(23)
        
        return f_e2_out
    

