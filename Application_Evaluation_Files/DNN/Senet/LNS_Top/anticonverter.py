def anticonverter(x, float_flag, Tri_overflow_one, n, conv_type=4):
    """
    主anticonverter模块
    输入:
        x: 32位二进制字符串
        float_flag: 是否计算浮点 (布尔值或字符串 '0'/'1')
        Tri_overflow_one: 溢出标志 (布尔值或字符串 '0'/'1')
        n: 定点小数位数 (5位整数)
    输出:
        x_output: 32位二进制字符串
    """
    # 确保输入格式正确
    if len(x) != 32:
        x = x.zfill(32)
    
    if isinstance(float_flag, bool):
        float_flag = '1' if float_flag else '0'
    elif isinstance(float_flag, int):
        float_flag = '1' if float_flag else '0'
    elif float_flag not in ['0', '1']:
        float_flag = '0'
    
    if isinstance(Tri_overflow_one, bool):
        Tri_overflow_one = '1' if Tri_overflow_one else '0'
    elif isinstance(Tri_overflow_one, int):
        Tri_overflow_one = '1' if Tri_overflow_one else '0'
    elif Tri_overflow_one not in ['0', '1']:
        Tri_overflow_one = '0'
    
    if isinstance(n, int):
        n_bin = int_to_bin(n, 5)
    else:
        n_bin = n.zfill(5) if len(n) < 5 else n[:5]
    
    # APP模块：f = x[21:0]
    f = bin_str_extract(x, 21, 0)
    # print("f:", f)
    if len(f) < 22:
        f = f.zfill(22)
    
    f_e2_out = app_module_anticonv(f, conv_type)
    # print("f_e2_out:", f_e2_out)
    # 计算shift: {3'b0, n} + x[29:22]
    x_29_22 = bin_str_extract(x, 29, 22)
    n_8bit = '000' + n_bin
    # print("n_8bit:", n_8bit)
    shift = bin_str_add(n_8bit, x_29_22, 8)
    # print("shift:", shift)
    
    # app_result = (f_e2_out[22]==1'b1) ? f_e2_out : {1'b1, 22'b0}
    # Verilog中f_e2_out[22]是MSB，对应Python的f_e2_out[0]
    if f_e2_out[0] == '1':  # f_e2_out[22]在Verilog中对应f_e2_out[0]在Python中
        app_result = f_e2_out
    else:
        app_result = '1' + '0' * 22
    # print("app_result:", app_result)
    # new_Shift_operation32: e = {app_result, 1'b0}
    e_24 = app_result + '0'
    if len(e_24) > 24:
        e_24 = e_24[:24]
    elif len(e_24) < 24:
        e_24 = e_24.zfill(24)
    # print("e_24:", e_24)
    result = new_shift_operation32(shift, e_24)
    # print("result:", result)

    
    # float_e_temp = 8'b01111111 + x[29:22]
    float_e_temp = bin_str_add('01111111', x_29_22, 8)
    # print("float_e_temp:", float_e_temp)
    # float_e = (float_e_temp == 8'b11111111) ? 8'b00000000 : float_e_temp
    if float_e_temp == '11111111':
        float_e = '00000000'
    else:
        float_e = float_e_temp
    
    # final_result_fix = (x[30]== 1'b1) ? (~result + 1'b1) : result
    x_30 = bin_str_extract(x, 30, 30)

    # print("x_30:", x_30)
    if x_30 == '1':
        neg_result = bin_str_negate(result)
        final_result_fix = bin_str_add(neg_result, '1', 32)
    else:
        final_result_fix = result
    # print("final_result_fix:", final_result_fix)

    
    # final_result_float = {x[30], float_e, app_result[21:0], 1'b0}
    x_30_bit = bin_str_extract(x, 30, 30)
    # print("x:", x)
    # print("x_30_bit:", x_30_bit)

    # app_result是23位，app_result[21:0]是低22位
    # Verilog中app_result[21:0]表示从bit 21到bit 0，在Python中对应app_result[1:23]（去掉MSB）
    app_result_low22 = app_result[1:] if len(app_result) >= 23 else app_result[1:].zfill(22)
    final_result_float = x_30_bit + float_e + app_result_low22 + '0'
    if len(final_result_float) > 32:
        final_result_float = final_result_float[:32]
    elif len(final_result_float) < 32:
        final_result_float = final_result_float.zfill(32)
    
    # final_result = (float_flag == 1'b1) ? final_result_float : final_result_fix
    if float_flag == '1':
        final_result = final_result_float
    else:
        final_result = final_result_fix
    
    # x_output = (x[31] == 1'b1 || Tri_overflow_one == 1'b1) ? 32'd0 : final_result
    x_31 = bin_str_extract(x, 31, 31)
    if x_31 == '1' or Tri_overflow_one == '1':
        x_output = '0' * 32
    else:
        x_output = final_result
    
    return x_output

