void matching(){
    int Kn = KH-KL;
    int Wn = Ncb-Kn;
    int maxCnt = (E+Wn-1)/Wn;
    int step = 2;
    for(int i = 0; i < Ncb; i++){
    	int sum = 0;
    	for(int j = 0; j < maxCnt; j++){
    		int idx = i+j*Wn;
    		if(i < KL){
    			sum += fint[idx];
    		}else if(i >= KH && idx-Kn < E){
    			sum += fint[idx-Kn];
   		    }else if(i >= KL && i < KH){
   		 	    sum = 0x81;
    		}
    	}
    	W_i[i] = sum >> step; // round(sum >> step)
    }
}


